// Byte-gate for the compiled stylesheet. Refuses to pass vacuously:
//   1. the artifact carries the generated-file header
//   2. freshness — rebuild into a temp dir, byte-compare with src/admin/theme/app.css.gen.ts
//   3. sentinels present (Tailwind v4 emits NOTHING for an unresolvable utility,
//      so presence, not absence, is the only honest test; list mirrors the
//      @source inline(...) in styles/app.css — keep the two lists in sync)
//   4. hygiene — no url() but data: in the artifact; no hex, no palette classes
//      in styles/chrome.css
import { readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const root = resolve(import.meta.dirname, "..");
const fail = (msg) => {
  console.error(`check-css: ${msg}`);
  process.exit(1);
};

// 1. header
const artifactPath = join(root, "src", "admin", "theme", "app.css.gen.ts");
const artifact = readFileSync(artifactPath, "utf8");
if (!artifact.startsWith("// generated by npm run css")) {
  fail("artifact header missing — run `npm run css`");
}
const css = JSON.parse(artifact.slice(artifact.indexOf('"'), artifact.lastIndexOf('"') + 1));

// 2. freshness
const rebuild = spawnSync(process.execPath, [join(root, "scripts", "build-css.mjs"), "--check"], {
  cwd: root,
  stdio: "inherit",
});
if (rebuild.status !== 0) fail("freshness check failed");

// 3. sentinels
const sentinels = [
  ".bg-background", ".text-foreground", ".bg-card", ".text-card-foreground",
  ".bg-muted", ".text-muted-foreground", ".bg-primary", ".text-primary-foreground",
  ".bg-secondary", ".text-secondary-foreground", ".border-border", ".rounded-xl", ".shadow-sm",
  ".h-16", ".min-h-svh", ".size-4", ".size-7", ".text-sm",
];
for (const s of sentinels) if (!css.includes(s)) fail(`sentinel utility missing from artifact: ${s}`);
if (!/\.dark\{?[^}]*--sidebar-primary:/.test(css.replace(/\n/g, ""))) {
  fail(".dark block with --sidebar-primary missing — theme.css did not embed");
}

// 4. hygiene
for (const m of css.matchAll(/url\(\s*['"]?([^)'"]+)/g)) {
  if (!m[1].startsWith("data:")) {
    fail(`non-data url() in artifact: ${m[1]} (fonts are data: faces in theme/fonts.ts, not url()s)`);
  }
}
const chrome = readFileSync(join(root, "styles", "chrome.css"), "utf8");
if (/#[0-9a-fA-F]{3,8}\b/.test(chrome)) fail("hex literal in styles/chrome.css — token roles only");
if (/\b(?:bg|text|border)-(?:red|blue|green|yellow|gray|slate|zinc|neutral|stone|orange|amber|lime|emerald|teal|cyan|sky|indigo|violet|purple|fuchsia|pink|rose)-\d{2,3}\b/.test(chrome)) {
  fail("Tailwind palette class in styles/chrome.css — token roles only");
}

console.error("check-css: ok");
