// Compiles styles/app.css (Tailwind v4 + theme.css + chrome.css,
// scanning src/) into src/admin/theme/app.css.gen.ts. Deterministic: `npm run
// check:css` rebuilds into a temp dir and byte-compares — never edit the .gen.ts.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");

const check = process.argv.includes("--check");
const out = join(root, "src", "admin", "theme", "app.css.gen.ts");
const tmp = mkdtempSync(join(tmpdir(), "nexus-css-"));
try {
  const cssPath = join(tmp, "app.css");
  execFileSync(
    process.execPath,
    [join(root, "node_modules", "@tailwindcss/cli", "dist", "index.mjs"),
     "-i", join(root, "styles", "app.css"), "-o", cssPath],
    { cwd: root, stdio: "inherit" },
  );
  const css = readFileSync(cssPath, "utf8");
  const module =
    `// generated by npm run css — do not edit\n` +
    `export const COMPILED_CSS = ${JSON.stringify(css)};\n`;
  if (check) {
    if (readFileSync(out, "utf8") !== module) {
      console.error("check-css: src/admin/theme/app.css.gen.ts is stale — run `npm run css`");
      process.exit(1);
    }
  } else {
    writeFileSync(out, module);
    console.error(`build-css: wrote src/admin/theme/app.css.gen.ts (${module.length} bytes)`);
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
